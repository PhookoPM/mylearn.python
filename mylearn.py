import numpy as np
def main():
    # Example of using NumPy to create an array
    arr = np.array([1, 2, 3, 4, 5])
    print("Array:", arr)

    # Example of basic operations
    print("Sum:", np.sum(arr))
    print("Mean:", np.mean(arr))
    print("Standard Deviation:", np.std(arr))
    print("Max:", np.max(arr)) 